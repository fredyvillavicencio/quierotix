<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;

class RecurrenteWebhookEvent extends Model
{
    /**
     * Proveedor de pagos asociado a estos registros.
     */
    public const PROVIDER = 'recurrente';

    /**
     * The attributes that are mass assignable.
     *
     * @var array<int, string>
     */
    protected $fillable = [
        'provider',
        'payment_key',
        'svix_id',
        'intent_id',
        'legacy_id',
        'event_type',
        'status',
        'raw_status',
        'receipt_number',
        'amount_in_cents',
        'currency',
        'customer_email',
        'customer_name',
        'checkout_id',
        'event_id',
        'participant_id',
        'payload',
        'processed_at',
        'last_error',
    ];

    /**
     * The attributes that should be cast.
     *
     * @var array<string, string>
     */
    protected $casts = [
        'receipt_number' => 'integer',
        'amount_in_cents' => 'integer',
        'payload' => 'array',
        'processed_at' => 'datetime',
    ];

    /**
     * Get the event associated with the payment.
     */
    public function event(): BelongsTo
    {
        return $this->belongsTo(Event::class);
    }

    /**
     * Get the participant generated by the payment.
     */
    public function participant(): BelongsTo
    {
        return $this->belongsTo(Participant::class);
    }

    /**
     * Determine whether the payment has already been fully processed.
     */
    public function isProcessed(): bool
    {
        return $this->processed_at !== null;
    }
}
